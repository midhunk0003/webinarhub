package com.wwitplwebinarhub.lms

import android.app.Activity
import android.graphics.Color
import android.graphics.Typeface
import android.os.Bundle
import android.os.Handler
import android.os.Looper
import android.util.Log
import android.view.Gravity
import android.view.View
import android.view.ViewGroup
import android.widget.FrameLayout
import android.widget.ProgressBar
import android.widget.TextView
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import us.zoom.sdk.JoinMeetingOptions
import us.zoom.sdk.JoinMeetingParams
import us.zoom.sdk.JoinMeetingParam4WithoutLogin
import us.zoom.sdk.MeetingParameter
import us.zoom.sdk.MeetingService
import us.zoom.sdk.MeetingServiceListener
import us.zoom.sdk.MeetingStatus
import us.zoom.sdk.ZoomSDK
import us.zoom.sdk.ZoomSDKInitParams
import us.zoom.sdk.ZoomSDKInitializeListener

/**
 * Native Android Activity used by the Flutter MethodChannel to join a Zoom meeting.
 *
 * Intent extras expected:
 *   meetingNumber, meetingPassword, userName, jwt
 *
 * IMPORTANT:
 * - `jwt` must be a valid Meeting SDK JWT generated by your backend.
 * - For meetings hosted outside your developer account, Zoom's current policy may
 *   require an approved SDK app and a ZAK or OBF authorization flow. This Activity
 *   does not create those tokens.
 */
class ZoomActivity : AppCompatActivity(), ZoomSDKInitializeListener {

    companion object {
        private const val TAG = "ZoomActivity"
        const val EXTRA_MEETING_NUMBER = "meetingNumber"
        const val EXTRA_MEETING_PASSWORD = "meetingPassword"
        const val EXTRA_USER_NAME = "userName"
        const val EXTRA_JWT = "jwt"
        const val EXTRA_ZAK = "zakToken"
        const val EXTRA_OBF = "obfToken"
    }

    private val mainHandler = Handler(Looper.getMainLooper())

    private var meetingNumber = ""
    private var meetingPassword = ""
    private var userName = "LMS User"
    private var meetingSdkJwt = ""
    private var zakToken = ""
    private var obfToken = ""

    private var meetingService: MeetingService? = null
    private var listenerRegistered = false
    private var joinRequested = false
    private var meetingJoined = false
    private var finishingWithResult = false
    private var sdkInitializationStarted = false

    private lateinit var loadingContainer: FrameLayout
    private lateinit var progressBar: ProgressBar
    private lateinit var titleText: TextView
    private lateinit var statusText: TextView

    private val meetingListener = object : MeetingServiceListener {
        override fun onMeetingStatusChanged(
            meetingStatus: MeetingStatus?,
            errorCode: Int,
            internalErrorCode: Int
        ) {
            Log.i(
                TAG,
                "Meeting status=$meetingStatus, errorCode=$errorCode, " +
                    "internalErrorCode=$internalErrorCode"
            )

            runOnUiThread {
                val status = meetingStatus?.toString().orEmpty().uppercase()

                when {
                    status.contains("INMEETING") -> {
                        meetingJoined = true
                        updateLoading(
                            "Connected",
                            "You have joined the Zoom session."
                        )
                        // Do not finish the Activity here. The Zoom meeting UI is active.
                        // We wait for an actual terminal meeting status.
                    }

                    status.contains("FAILED") -> {
                        val message =
                            "Zoom could not join this meeting. " +
                                "Error code: $errorCode (internal: $internalErrorCode)"
                        showErrorAndClose(message)
                    }

                    status.contains("ENDED") -> {
                        if (joinRequested) {
                            finishWithResult(meetingJoined)
                        }
                    }

                    status.contains("WAITING") ||
                        status.contains("CONNECTING") -> {
                        updateLoading(
                            "Joining webinar...",
                            "Connecting to the Zoom session."
                        )
                    }
                }
            }
        }

        override fun onMeetingParameterNotification(meetingParameter: MeetingParameter?) {
            Log.d(TAG, "Zoom meeting parameter notification received")
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setupLoadingScreen()

        meetingNumber = intent.getStringExtra(EXTRA_MEETING_NUMBER)?.trim().orEmpty()
        meetingPassword = intent.getStringExtra(EXTRA_MEETING_PASSWORD)?.trim().orEmpty()
        userName = intent.getStringExtra(EXTRA_USER_NAME)
            ?.trim()
            .takeUnless { it.isNullOrBlank() }
            ?: "LMS User"
        meetingSdkJwt = intent.getStringExtra(EXTRA_JWT)?.trim().orEmpty()
        zakToken = intent.getStringExtra(EXTRA_ZAK)?.trim().orEmpty()
        obfToken = intent.getStringExtra(EXTRA_OBF)?.trim().orEmpty()

        // Never log the actual passcode or JWT.
        Log.d(TAG, "Activity created")
        Log.d(TAG, "Meeting number present=${meetingNumber.isNotBlank()}")
        Log.d(TAG, "Password present=${meetingPassword.isNotBlank()}")
        Log.d(TAG, "User name present=${userName.isNotBlank()}")
        Log.d(TAG, "Meeting SDK JWT present=${meetingSdkJwt.isNotBlank()}")
        Log.d(TAG, "ZAK present=${zakToken.isNotBlank()}")
        Log.d(TAG, "OBF present=${obfToken.isNotBlank()}")

        when {
            meetingNumber.isBlank() -> {
                showErrorAndClose("Meeting ID is missing.")
                return
            }
            meetingPassword.isBlank() -> {
                showErrorAndClose("Meeting passcode is missing.")
                return
            }
            meetingSdkJwt.isBlank() -> {
                showErrorAndClose("Meeting SDK authentication token is missing.")
                return
            }
        }

        updateLoading("Preparing meeting...", "Connecting securely to Zoom.")
        mainHandler.postDelayed({
            if (!isFinishing && !isDestroyed && !finishingWithResult) {
                initializeZoom()
            }
        }, 250)
    }

    private fun setupLoadingScreen() {
        val root = FrameLayout(this).apply {
            setBackgroundColor(Color.rgb(12, 15, 22))
        }
        setContentView(root)

        loadingContainer = FrameLayout(this).apply {
            setBackgroundColor(Color.rgb(12, 15, 22))
        }
        root.addView(
            loadingContainer,
            FrameLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT,
                ViewGroup.LayoutParams.MATCH_PARENT
            )
        )

        val center = FrameLayout(this)
        val centerParams = FrameLayout.LayoutParams(
            ViewGroup.LayoutParams.MATCH_PARENT,
            dp(220)
        ).apply {
            gravity = Gravity.CENTER
            leftMargin = dp(28)
            rightMargin = dp(28)
        }
        loadingContainer.addView(center, centerParams)

        progressBar = ProgressBar(
            this,
            null,
            android.R.attr.progressBarStyleLarge
        ).apply {
            isIndeterminate = true
        }
        val progressParams = FrameLayout.LayoutParams(dp(48), dp(48)).apply {
            gravity = Gravity.TOP or Gravity.CENTER_HORIZONTAL
        }
        center.addView(progressBar, progressParams)

        titleText = TextView(this).apply {
            text = "Preparing meeting..."
            setTextColor(Color.WHITE)
            textSize = 20f
            typeface = Typeface.DEFAULT_BOLD
            gravity = Gravity.CENTER
        }
        val titleParams = FrameLayout.LayoutParams(
            ViewGroup.LayoutParams.MATCH_PARENT,
            ViewGroup.LayoutParams.WRAP_CONTENT
        ).apply {
            gravity = Gravity.TOP
            topMargin = dp(68)
        }
        center.addView(titleText, titleParams)

        statusText = TextView(this).apply {
            text = "Please wait while we prepare your webinar."
            setTextColor(Color.rgb(180, 185, 195))
            textSize = 14f
            gravity = Gravity.CENTER
        }
        val statusParams = FrameLayout.LayoutParams(
            ViewGroup.LayoutParams.MATCH_PARENT,
            ViewGroup.LayoutParams.WRAP_CONTENT
        ).apply {
            gravity = Gravity.TOP
            topMargin = dp(108)
        }
        center.addView(statusText, statusParams)
    }

    private fun updateLoading(title: String, status: String) {
        if (isFinishing || isDestroyed) return
        mainHandler.post {
            if (!isFinishing && !isDestroyed) {
                titleText.text = title
                statusText.text = status
                loadingContainer.visibility = View.VISIBLE
            }
        }
    }

    private fun hideLoading() {
        if (isFinishing || isDestroyed) return
        mainHandler.post {
            if (!isFinishing && !isDestroyed) {
                loadingContainer.visibility = View.GONE
            }
        }
    }

    private fun showErrorAndClose(message: String) {
        if (finishingWithResult) return
        Log.e(TAG, message)
        mainHandler.post {
            if (!isFinishing && !isDestroyed) {
                titleText.text = "Unable to join"
                statusText.text = message
                progressBar.visibility = View.GONE
                loadingContainer.visibility = View.VISIBLE
                Toast.makeText(this@ZoomActivity, message, Toast.LENGTH_LONG).show()
            }
        }
        mainHandler.postDelayed({
            finishWithResult(false)
        }, 2200)
    }

    private fun initializeZoom() {
        if (sdkInitializationStarted || finishingWithResult) return
        sdkInitializationStarted = true

        try {
            val zoomSDK = ZoomSDK.getInstance()
            val initParams = ZoomSDKInitParams().apply {
                jwtToken = meetingSdkJwt
                domain = "zoom.us"
                enableLog = true
            }

            Log.d(TAG, "Initializing Zoom Meeting SDK")
            zoomSDK.initialize(applicationContext, this, initParams)
        } catch (e: Exception) {
            Log.e(TAG, "Zoom SDK initialization threw an exception", e)
            showErrorAndClose("Could not initialize Zoom. Check the SDK configuration.")
        }
    }

    override fun onZoomSDKInitializeResult(
        errorCode: Int,
        internalErrorCode: Int
    ) {
        Log.i(
            TAG,
            "SDK initialization result: errorCode=$errorCode, " +
                "internalErrorCode=$internalErrorCode"
        )

        if (finishingWithResult) return

        if (errorCode != 0) {
            showErrorAndClose(
                "Zoom initialization failed. Error code: $errorCode " +
                    "(internal: $internalErrorCode)"
            )
            return
        }

        updateLoading("Joining webinar...", "Sending your join request to Zoom.")
        mainHandler.post {
            if (!isFinishing && !isDestroyed && !finishingWithResult) {
                joinMeeting()
            }
        }
    }

    override fun onZoomAuthIdentityExpired() {
        Log.e(TAG, "Zoom SDK authentication identity expired")
        showErrorAndClose("Zoom authentication expired. Please try again.")
    }

    private fun joinMeeting() {
        if (joinRequested || finishingWithResult) return

        val service = ZoomSDK.getInstance().meetingService
        if (service == null) {
            showErrorAndClose("Zoom meeting service is unavailable.")
            return
        }

        meetingService = service

        try {
            if (!listenerRegistered) {
                service.addListener(meetingListener)
                listenerRegistered = true
            }

            // Use the non-login authenticated parameter class when your backend
            // supplies a valid ZAK or OBF token. Never generate these tokens in Flutter.
            val params: JoinMeetingParams =
                if (zakToken.isNotBlank() || obfToken.isNotBlank()) {
                    JoinMeetingParam4WithoutLogin().apply {
                        displayName = userName
                        meetingNo = meetingNumber
                        password = meetingPassword
                        userType = MeetingService.USER_TYPE_API_USER

                        // Use the token appropriate to your approved Zoom flow.
                        // Normally pass ONE of these, not both.
                        if (zakToken.isNotBlank()) {
                            zoomAccessToken = zakToken
                        } else {
                            onBehalfToken = obfToken
                        }
                    }
                } else {
                    // JWT-only path: appropriate only when the meeting's security
                    // settings permit this join type (typically same-account meetings).
                    JoinMeetingParams().apply {
                        displayName = userName
                        meetingNo = meetingNumber
                        password = meetingPassword
                    }
                }

            val options = JoinMeetingOptions()

            joinRequested = true
            Log.i(TAG, "Calling joinMeetingWithParams; meeting number is present")

            val result = service.joinMeetingWithParams(this, params, options)
            Log.i(TAG, "joinMeetingWithParams returned=$result")

            if (result != 0) {
                joinRequested = false
                showErrorAndClose(
                    "Zoom rejected the join request. Error code: $result"
                )
            } else {
                // Do not treat return code 0 as proof that the meeting was joined.
                // The MeetingServiceListener reports the actual meeting status.
                updateLoading("Opening Zoom...", "Waiting for Zoom to connect.")
            }
        } catch (e: Exception) {
            joinRequested = false
            Log.e(TAG, "Exception while requesting Zoom join", e)
            showErrorAndClose("An error occurred while opening the Zoom meeting.")
        }
    }

    private fun finishWithResult(success: Boolean) {
        if (finishingWithResult) return
        finishingWithResult = true

        Log.i(TAG, "Finishing ZoomActivity; success=$success")

        mainHandler.removeCallbacksAndMessages(null)

        try {
            if (listenerRegistered) {
                meetingService?.removeListener(meetingListener)
                listenerRegistered = false
            }
        } catch (e: Exception) {
            Log.w(TAG, "Could not remove Zoom meeting listener", e)
        }

        setResult(
            if (success) Activity.RESULT_OK else Activity.RESULT_CANCELED
        )
        if (!isFinishing) finish()
    }

    override fun onBackPressed() {
        // Back from this loading Activity returns to Flutter. The Zoom SDK owns
        // its meeting UI while the meeting is active.
        if (meetingJoined) {
            finishWithResult(true)
        } else {
            finishWithResult(false)
        }
    }

    override fun onDestroy() {
        mainHandler.removeCallbacksAndMessages(null)
        try {
            if (listenerRegistered) {
                meetingService?.removeListener(meetingListener)
                listenerRegistered = false
            }
        } catch (e: Exception) {
            Log.w(TAG, "Error cleaning up meeting listener", e)
        }
        meetingService = null
        super.onDestroy()
    }

    private fun dp(value: Int): Int =
        (value * resources.displayMetrics.density).toInt()
}
